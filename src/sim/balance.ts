const isKnob = (o: unknown): o is Knob => !!o && typeof o === "object" && "v" in o && "min" in o;

function walk(spec: object, prefix: string, out: Dict, knobs: KnobInfo[]): Dict {
  for (const [key, node] of Object.entries(spec)) {
    const path = prefix ? `${prefix}.${key}` : key;
    if (isKnob(node)) {
      out[key] = node.v;
      knobs.push({ path, def: node.v, min: node.min, max: node.max, step: node.step, label: node.label });
    } else walk(node, path, (out[key] = {}), knobs);
  }
  return out;
}

export const KNOBS: KnobInfo[] = [];
export const BALANCE = walk(SPEC, "", {}, KNOBS) as Tree<typeof SPEC>;
export type Balance = typeof BALANCE;

export function getAt(path: string, B: Balance = BALANCE): number {
  return path.split(".").reduce<unknown>((o, key) => (o == null ? undefined : (o as Dict)[key]), B) as number;
}
// Ставит число по пути: зажимает в диапазон ручки и округляет до её шага. Возвращает то, что получилось.
export function setAt(path: string, value: number, B: Balance = BALANCE): number {
  const knob = KNOBS.find((q) => q.path === path);
  if (!knob) throw new Error(`В balance.ts нет ручки ${path}`);
  let v = Math.min(knob.max, Math.max(knob.min, Number(value)));
  v = Math.round((v - knob.min) / knob.step) * knob.step + knob.min;
  v = Number(v.toFixed(6));
  const keys = path.split(".");
  const last = keys.pop()!;
  (keys.reduce<unknown>((o, key) => (o as Dict)[key], B) as Dict)[last] = v;
  return v;
}
// «Было / стало» в эмуляторе и выгрузка значений: снимок — плоский объект { путь: число }.
export function snapshotBalance(B: Balance = BALANCE): Record<string, number> {
  return Object.fromEntries(KNOBS.map((q) => [q.path, getAt(q.path, B)]));
}
export function restoreBalance(snap: Record<string, number>, B: Balance = BALANCE): void {
  for (const [path, v] of Object.entries(snap)) setAt(path, v, B);
}
export function resetBalance(B: Balance = BALANCE): void {
  restoreBalance(Object.fromEntries(KNOBS.map((q) => [q.path, q.def])), B);
}
