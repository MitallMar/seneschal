// След ступени. gde — канал из словаря; без канала — дело само выходит на стол или видно всем. yasnost — если каталог её называет.
export interface ThreadTrace { gde?: Channel; text: string; yasnost?: Clarity }
// Ступень: что происходит; up — что ведёт вверх; stop — что останавливает; down — есть ли шаг назад и что он значит.
// traits — черты, которые на ступени приходят (come) и уходят (go), id из мешка; holder — кто держит; stol — когда ступень выходит на стол.
export interface ThreadStep {
  name: string;
  text: string;
  up?: string;
  stop?: string;
  down?: { est: boolean; text: string };
  traces: ThreadTrace[];
  stol?: string;
  traits?: { text: string; come: string[]; go: string[] };
  holder?: { roles: HolderRole[]; text: string };
  likho?: string;
  notes?: string[];
}
// Развязка — что остаётся. come и go — черты приходят и уходят; traits — черта названа, но не приходит и не уходит (толкает, крепнет, остаётся);
// next — нити, названные в развязке: переход; leaves — ушёл двор или человек. branch — развязка одной ветви нити.
export interface ThreadEnding {
  name: string;
  branch?: string;
  text: string;
  lines?: string[];
  come?: string[];
  go?: string[];
  traits?: string[];
  next?: ThreadId[];
  leaves?: ("dvor" | "chelovek")[];
}
// Где входит Сенешаль: when — ступень или название приёма, как в каталоге; ways — способы из 1.7, если они названы; cena — цена словами.
export interface ThreadEntry { when: string; text: string; ways: SeneschalWay[]; cena?: string }
// Кто может начать. opens, pushes, brakes — id черт мешка; stepTraits — черта, которая сама есть ступень нити.
export interface ThreadStart {
  opens: string[];
  pushes: string[];
  brakes: string[];
  stepTraits?: { trait: string; step: string }[];
  traitNotes: string[];
  signs?: string;
  povody: string[];
  other?: string[];
}
// Переход: в какую нить; uDrugogo — нить открывается не у человека, а у того, кого он задел.
export interface ThreadLink { nit: ThreadId; text?: string; uDrugogo?: boolean }
// Карточка-ступень: card — номер карточки колоды (src/data/deck.ts); obrazets — «по образцу карточки»; tekst — номер текста мира; без номера — карточки ещё нет.
export interface ThreadCard { name: string; card?: number; obrazets?: number; tekst?: number }
export interface ThreadDef {
  id: ThreadId;
  n: string;                 // номер записи в niti.md
  sign: ThreadSign;
  signNote?: string;         // оговорка к знаку: у «ребёнка на стороне» он зависит от брака
  about: string;
  start: ThreadStart;
  holders: HolderRole[];     // роли «кто держит», названные в записи
  steps: ThreadStep[];
  wakes: string;             // «просыпается»
  endings: ThreadEnding[];
  seneschal: ThreadEntry[];
  cena?: string;             // цена входа в целом, если каталог даёт её отдельной строкой
  links: string[];           // раздел «Связи» словами каталога
  to: ThreadLink[];          // «ведёт в»
  from: ThreadLink[];        // «входит из», «впадают»
  cards: ThreadCard[];
  notes?: { title: string; text: string }[]; // отдельные абзацы записи: решение автора, темп, оговорки
}
// Строка карты переходов (niti.md, раздел 6).
export interface ThreadMapRow { from: ThreadId[]; to: ThreadId[]; when: string; uDrugogo?: boolean }

