  ramka: "рамка", perevod: "назначение и перевод", podkhod: "подход и разговор", proverka: "проверка", sud: "суд", vykup: "выкуп и плата", zhrets: "жрец",
  udar: "удар по держателю", kryuchok: "крючок", zakryt_glaza: "закрыть глаза",
