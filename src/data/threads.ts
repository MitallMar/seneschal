// Движка нитей ещё нет: совет и колода каталог не читают. id и имена нитей — в словаре THREADS (src/data/portrait.ts); здесь — всё остальное.
// Тексты ступеней, следов и развязок — словами каталога. Ручек (niti.md, 1.10) здесь нет: они придут вместе с движком.
import type { Channel, ThreadId, HolderRole } from "./types";

// Знак нити: порочная держится на пороке или тайне; добрая — человек чего-то добивается; «ни то ни другое» — беда или стычка.
export type ThreadSign = "porochnaya" | "dobraya" | "nikakaya";
export const THREAD_SIGNS: Record<ThreadSign, string> = { porochnaya: "порочная", dobraya: "добрая", nikakaya: "ни то ни другое" };
// Ясность следа (niti.md, 1.5): чем ближе к развязке, тем ярче.
export type Clarity = "smutno" | "zametno" | "yasno" | "gromko";
export const CLARITY: Record<Clarity, string> = { smutno: "смутно", zametno: "заметно", yasno: "ясно", gromko: "громко" };
// Чем входит Сенешаль (niti.md, 1.7).
export type SeneschalWay = "ramka" | "perevod" | "podkhod" | "proverka" | "sud" | "vykup" | "zhrets" | "udar" | "kryuchok" | "zakryt_glaza";
